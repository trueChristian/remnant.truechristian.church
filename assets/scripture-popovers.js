/** Remnant's accessible, on-demand adapter for the pinned GetBible loader. */
import { Api } from './vendor/getbible/3.1.0/Api.js';
import { Memory } from './vendor/getbible/3.1.0/Memory.js';
import { Scripture } from './vendor/getbible/3.1.0/Scripture.js';

const DEFAULT_UI = Object.freeze({
  loading: 'Loading Scripture…', error: 'Scripture could not be loaded. Please try again.',
  readBible: 'Read in the Bible', close: 'Close', unavailable: 'This passage is unavailable.'
});
const SELECTOR = '.scripture-reference[data-reference][data-translation][data-scripture-id]';
const controllers = new WeakMap();

/** Strict input is generated by the build, never inferred from visible HTML. */
export function parseReference(reference) {
  if (typeof reference !== 'string' || reference.length > 200) throw new Error('Invalid reference');
  const match = /^([1-9]\d?) ([1-9]\d{0,2}):([1-9]\d{0,2}(?:-[1-9]\d{0,2})?(?:,[1-9]\d{0,2}(?:-[1-9]\d{0,2})?)*)$/.exec(reference);
  if (!match || Number(match[1]) > 84) throw new Error('Invalid reference');
  const verses = new Set();
  for (const part of match[3].split(',')) {
    const [start, end = start] = part.split('-').map(Number);
    if (end < start || end > 200 || end - start > 199) throw new Error('Invalid verse range');
    for (let n = start; n <= end; n++) verses.add(n);
  }
  return { book: Number(match[1]), chapter: Number(match[2]), verses };
}

export function parseSelection(reference, translations) {
  if (typeof reference !== 'string' || typeof translations !== 'string') throw new Error('Invalid selection');
  const refs = [...new Set(reference.split(';').map(value => value.trim()))];
  const versions = [...new Set(translations.split(';').map(value => value.trim()))];
  if (!refs.length || refs.length > 12 || !versions.length || versions.length > 4 ||
      versions.some(value => !/^[a-z][a-z0-9]{0,39}$/.test(value))) throw new Error('Invalid selection');
  refs.forEach(parseReference);
  return { refs, versions };
}

/** Validate the API/cache boundary, then use upstream Scripture/Reference objects. */
export function validateScripture(data, reference, translation) {
  const wanted = parseReference(reference);
  if (!data || typeof data !== 'object' || Array.isArray(data)) throw new Error('Invalid Scripture response');
  const entries = Object.values(data);
  if (entries.length !== 1) throw new Error('Unexpected Scripture chapters');
  const chapter = entries[0];
  if (!chapter || chapter.abbreviation !== translation || chapter.book_nr !== wanted.book ||
      chapter.chapter !== wanted.chapter || !Array.isArray(chapter.verses) ||
      !chapter.verses.length || chapter.verses.length > 200) throw new Error('Unexpected Scripture response');
  for (const field of ['translation', 'book_name', 'name']) {
    if (typeof chapter[field] !== 'string' || !chapter[field] || chapter[field].length > 500) throw new Error('Invalid Scripture metadata');
  }
  const seen = new Set();
  const verses = chapter.verses.map(verse => {
    if (!verse || !Number.isInteger(verse.verse) || !wanted.verses.has(verse.verse) ||
        seen.has(verse.verse) || (verse.chapter !== undefined && verse.chapter !== wanted.chapter) ||
        typeof verse.text !== 'string' || verse.text.length > 20000) throw new Error('Invalid Scripture verse');
    seen.add(verse.verse);
    return { verse: verse.verse, chapter: wanted.chapter, text: verse.text };
  });
  if (seen.size !== wanted.verses.size) throw new Error('Incomplete Scripture selection');
  const optional = field => typeof chapter[field] === 'string' && chapter[field].length <= 200 ? chapter[field] : '';
  return new Scripture({ chapter: {
    translation: chapter.translation, abbreviation: translation, book_nr: wanted.book,
    book_name: chapter.book_name, chapter: wanted.chapter, name: chapter.name, verses,
    direction: chapter.direction === 'RTL' ? 'RTL' : 'LTR',
    language: optional('language'), lang: optional('lang'), encoding: optional('encoding'), ref: reference
  } });
}

export class ScriptureClient {
  constructor(options = {}) { this.api = new Api(undefined, options); this.pending = new Map(); }
  get(reference, translation) {
    parseReference(reference);
    if (!/^[a-z][a-z0-9]{0,39}$/.test(translation)) throw new Error('Invalid translation');
    const key = `${translation}/${reference}`;
    if (!this.pending.has(key)) {
      const request = this.api.get(reference, translation).then(data => {
        try { return validateScripture(data, reference, translation); }
        catch (error) { Memory.remove(reference, translation); throw error; }
      }).finally(() => this.pending.delete(key));
      this.pending.set(key, request);
    }
    return this.pending.get(key);
  }
}

export function bibleReaderUrl(reference, base = 'https://getbible.life/') {
  // This feature's reader destination is fixed, never supplied by API text.
  base = 'https://getbible.life/';
  return base + [reference.abbreviation, reference.bookName, reference.chapter, reference.verseReference]
    .map(value => encodeURIComponent(String(value))).join('/');
}

function element(document, name, className, text) {
  const node = document.createElement(name);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

export function initScripturePopovers(document, options = {}) {
  if (controllers.has(document)) return controllers.get(document);
  const window = document.defaultView;
  let config = {};
  try { config = JSON.parse(document.querySelector('#page-config')?.textContent || '{}'); } catch { /* optional */ }
  const ui = { ...DEFAULT_UI, ...config.scriptureUi, ...options.ui };
  const client = options.client || new ScriptureClient();
  const groups = new Map();
  for (const marker of document.querySelectorAll(SELECTOR)) {
    try { parseSelection(marker.dataset.reference, marker.dataset.translation); }
    catch { marker.removeAttribute('role'); marker.removeAttribute('tabindex'); continue; }
    const id = marker.dataset.scriptureId;
    if (!groups.has(id)) groups.set(id, []);
    groups.get(id).push(marker);
  }
  if (!groups.size) return null;

  const popup = element(document, 'section', 'scripture-popover');
  popup.id = 'scripture-popover'; popup.hidden = true;
  popup.setAttribute('role', 'dialog'); popup.setAttribute('aria-modal', 'false');
  popup.setAttribute('aria-labelledby', 'scripture-popover-title');
  const header = element(document, 'div', 'scripture-popover__header');
  const title = element(document, 'h2', 'scripture-popover__title'); title.id = 'scripture-popover-title';
  const closeButton = element(document, 'button', 'scripture-popover__close', '×');
  closeButton.type = 'button'; closeButton.setAttribute('aria-label', ui.close);
  const content = element(document, 'div', 'scripture-popover__content');
  const status = element(document, 'p', 'scripture-popover__status'); status.setAttribute('role', 'status');
  header.append(title, closeButton); popup.append(header, status, content); document.body.append(popup);

  let active = null, serial = 0, hideTimer, showTimer, suppressFocus = null;
  const primary = group => group.find(node => node.tabIndex >= 0) || group[0];
  const cancelHide = () => window.clearTimeout(hideTimer);
  const position = () => {
    if (!active) return;
    const rect = active.anchor.getBoundingClientRect();
    const margin = 12, gap = 8, width = popup.offsetWidth, height = popup.offsetHeight;
    let left = document.documentElement.dir === 'rtl' ? rect.right - width : rect.left;
    left = Math.max(margin, Math.min(left, window.innerWidth - width - margin));
    const below = rect.bottom + gap;
    const top = below + height <= window.innerHeight - margin ? below : Math.max(margin, rect.top - height - gap);
    popup.style.left = `${left}px`; popup.style.top = `${top}px`;
  };
  const close = (restore = false) => {
    window.clearTimeout(showTimer); cancelHide(); serial++;
    if (!active) return;
    const previous = active;
    previous.group.forEach(node => node.setAttribute('aria-expanded', 'false'));
    active = null; popup.hidden = true; popup.removeAttribute('aria-busy');
    if (restore) {
      const target = primary(previous.group);
      suppressFocus = document.activeElement === target ? null : target;
      target.focus({ preventScroll: true });
    }
  };
  const scheduleHide = () => {
    cancelHide();
    hideTimer = window.setTimeout(() => {
      if (active && !active.pinned && !popup.matches(':hover') &&
          !popup.contains(document.activeElement) && !active.group.includes(document.activeElement)) close();
    }, 180);
  };
  const show = async (marker, pin = false, focus = false) => {
    cancelHide(); window.clearTimeout(showTimer);
    const group = groups.get(marker.dataset.scriptureId);
    if (active?.group === group) {
      active.pinned ||= pin;
      if (focus) closeButton.focus();
      return;
    }
    close();
    const requestSerial = ++serial;
    active = { group, anchor: marker, pinned: pin };
    group.forEach(node => node.setAttribute('aria-expanded', 'true'));
    title.textContent = marker.dataset.scriptureLabel || group.map(node => node.textContent).join('');
    content.replaceChildren(); status.textContent = ui.loading; popup.hidden = false;
    popup.setAttribute('aria-busy', 'true'); position();
    if (focus) closeButton.focus();
    try {
      const { refs, versions } = parseSelection(marker.dataset.reference, marker.dataset.translation);
      const results = await Promise.all(refs.flatMap(ref => versions.map(version => client.get(ref, version))));
      if (!active || requestSerial !== serial) return;
      for (const scripture of results) scripture.forEachReference(reference => {
        const block = element(document, 'section', 'scripture-popover__passage');
        block.dir = reference.textDirection === 'RTL' ? 'rtl' : 'ltr';
        if (/^[a-zA-Z]{2,3}(?:-[a-zA-Z0-9]{2,8})*$/.test(reference.languageCode)) block.lang = reference.languageCode;
        // Like Loader's show-local-reference option, the dialog title already
        // labels a single passage. Only split selections need section labels.
        if (refs.length > 1) block.append(element(document, 'h3', 'scripture-popover__reference', reference.reference));
        block.append(element(document, 'p', 'scripture-popover__translation', reference.translation));
        for (const verse of reference.verses) {
          const paragraph = element(document, 'p', 'scripture-popover__verse');
          paragraph.append(element(document, 'sup', '', `${verse.verse} `), document.createTextNode(verse.text));
          block.append(paragraph);
        }
        const link = element(document, 'a', 'scripture-popover__reader', ui.readBible);
        link.href = bibleReaderUrl(reference, config.scriptureReaderBase); link.rel = 'noopener noreferrer';
        block.append(link); content.append(block);
      });
      status.textContent = '';
    } catch {
      if (!active || requestSerial !== serial) return;
      status.textContent = ui.error;
      const link = element(document, 'a', 'scripture-popover__reader', ui.readBible);
      link.href = 'https://getbible.life/'; link.rel = 'noopener noreferrer';
      content.append(link);
    } finally {
      if (active && requestSerial === serial) { popup.removeAttribute('aria-busy'); position(); }
    }
  };

  for (const group of groups.values()) for (const marker of group) {
    marker.dataset.scriptureReady = 'true';
    marker.setAttribute('role', 'button'); marker.tabIndex = marker === group[0] ? 0 : -1;
    marker.setAttribute('aria-haspopup', 'dialog'); marker.setAttribute('aria-controls', popup.id);
    marker.setAttribute('aria-expanded', 'false');
    if (!marker.hasAttribute('aria-label')) marker.setAttribute('aria-label', marker.dataset.scriptureLabel || group.map(node => node.textContent).join(''));
    marker.addEventListener('pointerenter', event => {
      if (event.pointerType !== 'mouse') return;
      cancelHide(); window.clearTimeout(showTimer);
      if (!active?.pinned) showTimer = window.setTimeout(() => show(marker), 150);
    });
    marker.addEventListener('pointerleave', () => { window.clearTimeout(showTimer); scheduleHide(); });
    marker.addEventListener('focus', () => {
      if (suppressFocus === marker) { suppressFocus = null; return; }
      show(marker);
    });
    marker.addEventListener('click', event => {
      event.preventDefault();
      if (active?.group === group && active.pinned) close(popup.contains(document.activeElement));
      else show(marker, true);
    });
    marker.addEventListener('keydown', event => {
      if (['Enter', ' ', 'ArrowDown'].includes(event.key)) { event.preventDefault(); show(marker, true, true); }
      else if (event.key === 'Tab' && !event.shiftKey && active?.group === group) {
        event.preventDefault(); active.pinned = true; closeButton.focus();
      }
    });
  }
  closeButton.addEventListener('click', () => close(true));
  popup.addEventListener('pointerenter', cancelHide);
  popup.addEventListener('pointerleave', scheduleHide);
  popup.addEventListener('keydown', event => {
    if (event.key === 'Tab' && event.shiftKey && document.activeElement === closeButton) {
      event.preventDefault(); close(true);
    } else if (event.key === 'Tab' && !event.shiftKey && active) {
      const inside = [...popup.querySelectorAll('button,a[href]')];
      if (document.activeElement === inside.at(-1)) {
        const trigger = primary(active.group);
        const outside = [...document.querySelectorAll('a[href],button,input,select,textarea,[tabindex="0"]')]
          .filter(node => !popup.contains(node) && !node.disabled && node.getClientRects().length);
        const next = outside[outside.indexOf(trigger) + 1];
        if (next) { event.preventDefault(); close(); next.focus(); }
      }
    }
  });
  document.addEventListener('keydown', event => {
    if (event.key === 'Escape' && active) { event.preventDefault(); close(true); }
  });
  document.addEventListener('pointerdown', event => {
    if (active && !popup.contains(event.target) && !active.group.some(node => node.contains(event.target))) close();
  });
  document.addEventListener('focusin', event => {
    if (active && !popup.contains(event.target) && !active.group.some(node => node.contains(event.target))) close();
  });
  window.addEventListener('resize', position);
  window.addEventListener('scroll', position, { passive: true });
  window.addEventListener('pagehide', () => close());
  const controller = { close, popup }; controllers.set(document, controller); return controller;
}

if (typeof document !== 'undefined') {
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', () => initScripturePopovers(document), { once: true });
  else initScripturePopovers(document);
}
